#!/usr/bin/env python3
"""
build.py - creates images/manifest.js and images/manifest.json
Usage:  python build.py        (or python3 build.py)
Same job as build.js; use whichever you have installed.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DIR = os.path.join(HERE, "images")
EXT = ["jpg", "jpeg", "png", "webp", "gif", "avif", "bmp", "svg"]

if not os.path.isdir(DIR):
    sys.exit('ERROR: folder "images" not found next to build.py')

files = os.listdir(DIR)
by_lower = {f.lower(): f for f in files}

lst = []
n = 1
while True:
    matches = [by_lower[f"image{n}.{e}"] for e in EXT if f"image{n}.{e}" in by_lower]
    if not matches:
        break
    if len(matches) > 1:
        print(f"WARNING: several files named image{n}.* found ({', '.join(matches)}). Using {matches[0]}. Remove the others.")
    lst.append("images/" + matches[0])
    n += 1

pat = re.compile(r"^image(\d+)\.(" + "|".join(EXT) + r")$", re.I)
ignored = [f for f in files if (m := pat.match(f)) and int(m.group(1)) >= n]
if ignored:
    print(f"WARNING: number image{n} is missing, so these files are NOT used: {', '.join(ignored)}")

if not lst:
    sys.exit("ERROR: no images found. Name them image1.jpg, image2.png, image3.webp ... and put them in the images folder.")

with open(os.path.join(DIR, "manifest.json"), "w") as f:
    f.write(json.dumps(lst, indent=2) + "\n")
with open(os.path.join(DIR, "manifest.js"), "w") as f:
    f.write("// Auto-generated by build.py - do not edit by hand.\nwindow.IMAGE_MANIFEST = " + json.dumps(lst, indent=2) + ";\n")

print(f"Done. {len(lst)} image(s) in order:")
for i, p in enumerate(lst, 1):
    print(f"  {i}. {p}")
