#!/usr/bin/env node
/*
  build.js - creates images/manifest.js and images/manifest.json
  Usage:  node build.js
  Finds image1, image2, image3 ... in the "images" folder (any supported extension)
  and stops at the first missing number.
*/
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "images");
const EXT = ["jpg", "jpeg", "png", "webp", "gif", "avif", "bmp", "svg"];

if (!fs.existsSync(dir)) {
  console.error('ERROR: folder "images" not found next to build.js');
  process.exit(1);
}

const files = fs.readdirSync(dir);
const byLower = new Map();
for (const f of files) byLower.set(f.toLowerCase(), f);

const list = [];
let n = 1;
for (;;) {
  const matches = EXT.map(e => byLower.get(`image${n}.${e}`)).filter(Boolean);
  if (!matches.length) break;
  if (matches.length > 1) {
    console.warn(`WARNING: several files named image${n}.* found (${matches.join(", ")}). Using ${matches[0]}. Remove the others.`);
  }
  list.push("images/" + matches[0]);
  n++;
}

// Report numbered images that are ignored because of a gap in the numbering.
const re = new RegExp(`^image(\\d+)\\.(${EXT.join("|")})$`, "i");
const ignored = files.filter(f => {
  const m = f.match(re);
  return m && parseInt(m[1], 10) >= n;
});
if (ignored.length) {
  console.warn(`WARNING: number image${n} is missing, so these files are NOT used: ${ignored.join(", ")}`);
}

if (!list.length) {
  console.error("ERROR: no images found. Name them image1.jpg, image2.png, image3.webp ... and put them in the images folder.");
  process.exit(1);
}

fs.writeFileSync(path.join(dir, "manifest.json"), JSON.stringify(list, null, 2) + "\n");
fs.writeFileSync(
  path.join(dir, "manifest.js"),
  "// Auto-generated by build.js - do not edit by hand.\nwindow.IMAGE_MANIFEST = " + JSON.stringify(list, null, 2) + ";\n"
);

console.log(`Done. ${list.length} image(s) in order:`);
list.forEach((p, i) => console.log(`  ${i + 1}. ${p}`));
